/** فقط نام‌ها — سوخت فهرست پیشنهادِ مقدار برای تنوع «رنگ» */
export const COLOR_NAMES: string[] = NAMED_COLORS.map((c) => c.name)

const BY_NAME: Record<string, string> = Object.fromEntries(
  NAMED_COLORS.map((c) => [c.name, c.hex]),
)
/** چند نام مترادف که در فهرست پیشنهاد نمی‌آیند ولی اگر کاربر بنویسد باید شناخته شوند */
const ALIASES: Record<string, string> = {
  'سیاه': '#20262b',
  'طوسی': '#8a949b',
  'نقرآبی': '#5aa9d6',
}

/** رنگِ یک نام؛ نامِ ناشناخته → خاکستریِ خنثی (کاربر می‌تواند از پالت عوضش کند) */
export function colorForValue(label: string): string {
  const key = label.trim()
  return BY_NAME[key] ?? ALIASES[key] ?? '#9aa6ad'
}
