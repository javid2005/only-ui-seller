/**
 * منبع واحدِ «چه چیزی برای این دسته‌بندی معمول است».
 *
 * چرا یک فایل داده و نه چند لیست پراکنده: سه جای مختلف به همین دانش نیاز دارند —
 * چیپ‌های پیشنهادی تنوع، مقادیر پیشنهادی هر تنوع، و مشخصه‌های پیشنهادی محصول —
 * و اگر هر کدام لیست خودش را داشته باشد، با اولین ویرایش از هم واگرا می‌شوند.
 *
 * این ساختار عمداً **درختی و تخت‌خوان** است تا بعداً از پنل مدیریت ویرایش شود:
 *   دسته‌بندی → تنوع‌ها → مقادیر
 *   دسته‌بندی → مشخصه‌ها → نمونه‌مقدار
 * هیچ منطقی داخلش نیست؛ فقط داده. جایگزینی‌اش با خروجی API یعنی عوض‌کردن همین
 * یک شیء، بدون دست‌زدن به هیچ کامپوننتی.
 *
 * ⚠️ مقادیر رنگ اینجا **نام** فارسی‌اند، نه hex: نگاشت نام→رنگ در `data.ts`
 * (`colorForValue`) است تا یک جا بماند.
 */

export interface OptionSuggestion {
  /** عنوان تنوع — همان چیزی که روی چیپ پیشنهادی دیده می‌شود */
  title: string
  /** مقادیر رایج؛ در فیلد «مقادیر …» به‌صورت پیشنهاد ظاهر می‌شوند */
  values: string[]
  /** در نوار پیشنهادِ کوتاه (خارج از «انتخاب سفارشی») هم دیده شود؟ */
  primary?: boolean
}

export interface AttributeSuggestion {
  title: string
  /**
   * مقادیر رایجِ همین مشخصه.
   *
   * یک نمونه کافی نبود: کاربر عنوان را از فهرست برمی‌داشت و بعد باید مقدار را
   * از صفر می‌نوشت. اولین مقدار نقشِ «مثال» را هم بازی می‌کند (placeholder و
   * راهنما)، بقیه در فهرست پیشنهادِ فیلدِ مقدار می‌آیند.
   */
  values: string[]
}

export interface CategoryKnowledge {
  options: OptionSuggestion[]
  attributes: AttributeSuggestion[]
  /** نمونهٔ پرشدهٔ یک محصول همین دسته — برای بخش «مثال» در راهنما */
  sample: { name: string; shortDescription: string; tags: string[] }
}

