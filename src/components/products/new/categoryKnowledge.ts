/** مقادیر پیشنهادی یک تنوع — نام تنوع ممکن است دست‌نویس باشد، پس تطبیق نرم است */
export function valuesForOption(category: string, optionTitle: string): string[] {
  const title = optionTitle.trim()
  if (!title) return []
  const list = optionsForCategory(category)
  const exact = list.find((o) => o.title === title)
  if (exact) return exact.values
  const loose = list.find((o) => title.includes(o.title) || o.title.includes(title))
  return loose?.values ?? []
}

